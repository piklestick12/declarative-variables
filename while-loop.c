#include <stdio.h>

// While loop:
int main()
{
    int i = 0;

    while (i <= 10)
    {
        printf("While loop:\n");
        printf("%d\n", i);
        i++;
    }

    // For Loop:
    for (int i = 2; i <= 20; i + 2)
    {
        printf("For Loop:\n");
        printf("%d\n", i);

        return 0;
    }
}